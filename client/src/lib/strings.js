export const STRINGS = { en, et, ru, uk, ur, hi };

const fill = (text, values) => String(text).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');

export function strings(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  const t = (key, values = {}) => {
    const value = table[key] ?? STRINGS.en[key] ?? key;
    return Array.isArray(value) ? value.map((line) => fill(line, values)) : fill(value, values);
  };
  return t;
}

